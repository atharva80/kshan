"""Renders a results JSON (from run.py) as eval/results.md. Every number in the tables
comes straight from that file."""


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}"


def num(x, digits=3):
    return "–" if x is None else f"{x:.{digits}f}"


def ms(x):
    return "–" if x is None else f"{x:.0f}"


def _get(system, split, group, key):
    return system["summary"][split].get(group, {}).get(key)


def headline(systems: dict, names: list[str], split: str) -> str:
    lines = ["| System | Charades R@1 | R@10 | MRR | moment@1 | FLEURS sentence R@1 | R@10 | FLEURS keyword R@1 | R@10 "
             "| no-answer FP | p50 ms | p95 ms |",
             "|---|" + "---:|" * 11]
    for name in names:
        s = systems.get(name)
        if not s:
            continue
        lat = s.get("latency") or {}
        lines.append("| " + " | ".join([
            name,
            pct(_get(s, split, "charades_sentence", "R@1")), pct(_get(s, split, "charades_sentence", "R@10")),
            num(_get(s, split, "charades_sentence", "MRR")), pct(_get(s, split, "charades_sentence", "moment@1")),
            pct(_get(s, split, "fleurs_sentence", "R@1")), pct(_get(s, split, "fleurs_sentence", "R@10")),
            pct(_get(s, split, "fleurs_keyword", "R@1")), pct(_get(s, split, "fleurs_keyword", "R@10")),
            pct(_get(s, split, "all", "noans_FP")), ms(lat.get("p50_ms")), ms(lat.get("p95_ms")),
        ]) + " |")
    return "\n".join(lines)


def by_language(systems: dict, names: list[str], split: str) -> str:
    cols = [(t, lang) for t in ("fleurs_sentence", "fleurs_keyword") for lang in ("hi_in", "mr_in", "en_us")]
    head = " | ".join(f"{'sentence' if t == 'fleurs_sentence' else 'keyword'} {lang[:2]} R@1 / R@10" for t, lang in cols)
    lines = [f"| System | {head} |", "|---|" + "---:|" * len(cols)]
    for name in names:
        s = systems.get(name)
        if not s:
            continue
        cells = [f"{pct(_get(s, split, f'{t}:{lang}', 'R@1'))} / {pct(_get(s, split, f'{t}:{lang}', 'R@10'))}"
                 for t, lang in cols]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def markdown(out: dict, filename: str) -> str:
    systems = out["systems"]
    main = [n for n in ("immich_before", "immich_after", "vsearch (live)", "proxy (live)", "vsearch_fixed (live)",
                          "proxy_fixed (live)") if n in systems]
    ablations = ["vsearch"] + [n for n in systems if n.startswith("ablation")]
    fixes = ["vsearch"] + [n for n in systems if n.startswith(("fix", "variant"))]
    sim = out.get("proxy_simulated", {})
    proxy_rows = {f"search bar via {n}": {"summary": v["summary"]} for n, v in sim.items()}

    n_test = {k: v.get("n") for k, v in systems[main[0]]["summary"]["test"].items()} if main else {}
    parts = [
        "# Benchmark results",
        "",
        f"Generated by `eval/run.py` from `eval/results/{filename}` (commit `{out['commit']}`"
        + (", uncommitted changes" if out.get("dirty") else "") + f", {out['date']}). "
        "Definitions, datasets and how to reproduce: [docs/evaluation.md](../docs/evaluation.md).",
        "",
        "Recall and moment numbers are percentages. **Test split** unless stated; thresholds and "
        "fusion were chosen on the dev split only.",
        "",
        f"Test queries: Charades {n_test.get('charades_sentence')}, FLEURS sentence {n_test.get('fleurs_sentence')}, "
        f"FLEURS keyword {n_test.get('fleurs_keyword')}, no-answer "
        f"{systems[main[0]]['summary']['test']['all'].get('n_noans') if main else '–'}.",
        "",
        "## Headline (test)",
        "",
        headline(systems, main, "test"),
        "",
        "`immich_before`: plain Immich before indexing (it only embeds a video's thumbnail). "
        "`immich_after`: plain Immich after vsearch's write-back, i.e. the unmodified phone app. "
        "`vsearch`: the companion search page. `proxy`: Immich's search bar routed through vsearch. "
        "`(live)` rows were measured against the running services; rows without it are the same "
        "code re-ranking saved candidates (see Consistency).",
        "",
        "## By language, FLEURS (test)",
        "",
        by_language(systems, main, "test"),
        "",
        "## Ablations (test)",
        "",
        headline(systems, ablations, "test"),
        "",
        "## Fixes, before and after (test)",
        "",
        headline(systems, fixes, "test"),
        "",
    ]
    for n in fixes:
        if n in systems and systems[n].get("description"):
            parts.append(f"- **{n}**: {systems[n]['description']}")
    if proxy_rows:
        parts += ["", "### The search bar (proxy), re-ranked offline with each configuration (test)", "",
                  headline({**proxy_rows, **{k: systems[k] for k in main if k.startswith('immich')}},
                           [k for k in main if k.startswith("immich")] + list(proxy_rows), "test")]
    c, ix = out.get("consistency"), out.get("indexing")
    parts += ["", "## Consistency and indexing", ""]
    for live_name, v in (c or {}).items():
        parts.append(f"- Offline re-ranking with `{v['config']}` reproduces the live API (`{live_name}`) top 10 "
                     f"exactly on {pct(v['top10_identical'])}% of {v['n']} queries.")
    if ix:
        parts.append(f"- Indexed {ix['done']} of {ix['videos']} videos ({ix['failed']} failed), "
                     f"{ix['video_hours']:.2f} h of video, in {ix['wall_seconds'] / 60:.0f} min wall time; "
                     f"{ix['seconds_per_video_minute']:.1f} s of processing per minute of video (median {ix['median_seconds_per_video_minute']:.1f}; {ix['median_seconds_per_video']:.1f} s per video) "
                     "(frames + OCR + Whisper with translation + bge-m3, RTX 2000 Ada 8 GB).")
    parts += ["", "## Appendix: dev split", "", headline(systems, main, "dev"), "", headline(systems, fixes, "dev"), ""]
    return "\n".join(parts)
